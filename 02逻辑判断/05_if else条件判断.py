"""
 if满足条件会执行相应的代码语句，如果不满足呢？
 有没有不满足的情况下，可供执行的代码呢？
 if else语句可以实现
 if 条件：
     满足条件时要做的事 1
     满足条件时要做的事 2
     满足条件时要做的事 3
     ....
 else:
     不满足条件时要做的事 1
     不满足条件时要做的事 2
     不满足条件时要做的事 3
     ....
"""
print("欢迎来到天堂游乐场，未成年免费，成年人需收费。")
age = int(input("请输入您的年龄："))
if age >= 18:
    print("您已成年，需补票20元。")  # 条件成立时执行

else:   # 不需要条件，与if是同一个条件内，只有满足不满足的分叉 就近原则：与最近的if语句搭对
        # if和else之间不要出现其他语句，否则报错 else必须配合if出现
    print("您是未成年，可以免费游玩。")  # 条件不成立时执行 四个空格缩进
print("欢迎！")