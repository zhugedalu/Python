# 引号嵌套
# 双引号写法
name = "诸葛孔明"

# 单引号写法(为了避免过多的转义)
name = '周瑜'

# 有个字符串是："太古里"
# address = ""太古里""  就近匹配 双引号和最近的双引号匹配后，只剩太古里，报错。
address = '"太古里"'
print(address)
# 有个字符串是：'太古里'
address2 = "'太古里'"
print(address2)

# 三引号写法
# 如果没有变量接收，作为多行注释存在。
# 如果有变量接收值，就是字符串。
# 复制大量文本可以使用
info = """我叫诸葛亮"""
print(info)
info1 = """我年纪撒比就开始"查看的"是不成'熟'考虑时间"""
print(info1)