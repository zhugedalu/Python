"""
这个代码文件演示的是变量的基础应用；
变量，记录数据；
变量名称 = 变量的值（每个变量都有自己存储的值或者内容，称之为变量值）；
= 代表赋值，表示将等号右边的值，赋予给左侧的变量；
变量的特性，变量存储的数据是可以改变的。
"""

# 将50这个值，存入变量money中
money = 100
name = "诸葛大璐"     # 诸葛大璐是字面量中的字符串，需要双引号包围，而name是变量不是字面量，不需要双引号。

# print语句可以将字面量的内容在屏幕上显示，那么变量呢？
# print语句也可以将变量的值显示在屏幕上
# 也能证明money和50的值是等价的，即证明了moey内部存储了50这 个值
print(money)
print(name)
print("---------------------------")

# 变量存放的值是可以改变的，语法就是再次使用变量的赋值语句，即重新赋值。
money  =  500
name = "宝宝"

print(money)
print(name)

