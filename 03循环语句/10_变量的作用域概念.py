# for 临时变量 in 待处理数据集：
#     循环满足条件时执行的代码
# 回看for循环的语法，从数据集（序列）中取出的数据赋值给：临时变量，为什么时临时变量呢？
# 临时变量，在编程规范上，作用范围（作用域），只限定在for循环内部。
# 如果在for循环外部访问临时变量：
# 实际上是可以访问到的，在编程规范上，是不允许、不建议这么做的。
# 符合所有带冒号的 
num = 10                # 同缩进和下层（内层）缩进都可以访问到
age = 0                 # 如需访问临时变量，可以预先在循环外定义它
for i in range(5):
    age = 100
    print(num)          # num变量和for循环同级，所以for循环内部语句可以访问到num变量
print(age)              # 右缩进可以访问左缩进，反之不可以