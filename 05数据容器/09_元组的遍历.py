# while循环
print("-------while循环--------")
t1 = (1,2,3,4,5,6,7)
index = 0
while index < len(t1):
    print(t1[index])
    index += 1

# for循环
print("------for循环---------")
t1 = (1,2,3,4,5,6,7)
for i in t1:
    print(i)


