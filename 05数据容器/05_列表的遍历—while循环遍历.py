"""
数据容器可以存储多个元素，那么就会有需求从容器内依次取出元素进行操作
将容器内的元素依次取出进行处理的行为，称之为：遍历、迭代。
如何遍历列表的元素呢？

如何在循环中取出列表的元素呢？
使用列表[下标]的方式取出

循环条件如何控制呢？循环条件为：
1. 定义一个变量表示下标，从0开始
2. 循环条件为： 下标值 < 列表的元素数量(列表的长度)
"""
index = 0           # 控制因子
lst = [1,5,67,89,34,57767,78,9,34,54578,467,223,22,23,57]
while index < len(lst):         # 条件判断
    # i = lst[index]
    # print(i)
    print(lst[index])
    index += 1          # 因子更新
