# 根据下标（索引）取出数据
t1 = (1,2,"hello")
print(t1[2])

# 根据index()，查找特定元素的第一个匹配项   和list一样
t1 = (1,2,"hello")
print(t1.index("hello"))

# 根据count(),统计某个数据在元组内出现的次数
t1 = (1,2,"hello",1,56,89,1,2,3,41,1,1325,667,8)
print(t1.count(1))

# 统计元组内的元素个数 len(元组)
t1 = (1,2,"hello",1,56,89,1,2,3,41,1,1325,667,8)
print(len(t1))



