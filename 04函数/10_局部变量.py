"""
变量作用域指的是变量的作用范围（变量在哪里可用，在哪里不可用）
主要分为两类：局部变量和全局变量

所谓局部变量是```定义在函数体内部的变量，即只在函数体内部生效```
"""
num = None # 全局变量
def testA():
    # num是局部变量，作用域（生命周期）仅在函数内部有效
    # 局部变量：写在函数内部的变量（也叫临时变量）
    num = 100
    print("内部输出：",num)
testA()
print("外部输出：",num)

# 当函数执行完成后，临时变量（局部变量）num已经不存在了
# 即num存在的时间只有在调用函数的那一会儿
# 在print(num)语句执行的这个地方，num已经不存在了
# print(num) 会报错，因为变量num在函数体内部的变量，在函数外部访问会立即报错(左访右不可以，)
# 局部变量的作用：在函数体内部，临时保存数据，即当函数调用完成后，则销毁局部变量