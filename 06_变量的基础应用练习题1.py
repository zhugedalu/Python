""""
请在程序中，定义如下变量：
（1）钱包余额（变量名：money），初始余额为50；
请通过程序计算，在购买了：
（1）冰淇淋10元
（2）可乐5元
 后，钱包余额还剩余多少元。请通过print语句按照下图所示，进行输出：
 当前钱包余额：50元
 购买了冰淇淋，花费： 10元
 购买了可乐，花费： 5元
 最终，钱包剩余：35元
"""

money = 50
print("当前钱包余额:",money,"元")
print("购买了冰淇淋，花费：",10,"元")
print("购买了可乐，花费：",5,"元")
# 写法1
# print("最终，钱包剩余：",money - 10 -5 ,"元")
# 写法2,先计算右侧结果，在赋予左侧变量
money = money - 10 - 5
print("最终，钱包剩余：",money,"元")